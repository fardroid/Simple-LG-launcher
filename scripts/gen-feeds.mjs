// Generates src/data/editions.inc: the Google News editions by country (data/editions.json), and the names of the
// countries and of the languages of the editions in the launcher's languages, from node's Intl.
// Run: node scripts/gen-feeds.mjs

import {readFileSync, writeFileSync} from 'node:fs';

const EDITIONS = JSON.parse(readFileSync(new URL('../data/editions.json', import.meta.url), 'utf8'));
const LANGS = {en: 'en', ru: 'ru', es: 'es', fr: 'fr', de: 'de', it: 'it', pt: 'pt', tr: 'tr', uk: 'uk', zh: 'zh-CN', ja: 'ja', ko: 'ko', pl: 'pl'};
const q = (s) => JSON.stringify(s);
let out = '// Generated by scripts/gen-feeds.mjs from data/editions.json and node ' + process.version + ' (Intl). Do not edit.\n';
out += 'static const Edition EDITIONS[] = {\n';
for (const code of Object.keys(EDITIONS).sort())
	for (const e of EDITIONS[code].editions) out += `\t{${q(code)}, ${q(e[0])}, ${q(e[1])}, ${q(e[2])}},\n`;
out += '};\n';
out += 'static const CountryName COUNTRY_NAMES[] = {\n';
for (const code of Object.keys(EDITIONS).sort()) {
	const names = Object.entries(LANGS).map(([lang, tag]) => {
		let n = EDITIONS[code].name;
		try { const d = new Intl.DisplayNames([tag], {type: 'region'}).of(code); if (d && d !== code) n = d; } catch { /* English */ }
		return q(n);
	});
	out += `\t{${q(code)}, {${names.join(', ')}}},\n`;
}
out += '};\n';
// the languages of the editions, named in each of the launcher's languages (CountryPicker.tsx asks Intl.DisplayNames for them)
const editionLangs = [...new Set(Object.values(EDITIONS).flatMap((c) => c.editions.map((e) => e[0])))].sort();
out += 'static const CountryName LANGUAGE_NAMES[] = {\n';
for (const code of editionLangs) {
	const names = Object.entries(LANGS).map(([, tag]) => {
		let n = code;
		try { const d = new Intl.DisplayNames([tag], {type: 'language'}).of(code); if (d && d !== code) n = d; } catch { /* the code */ }
		return q(n);
	});
	out += `\t{${q(code)}, {${names.join(', ')}}},\n`;
}
out += '};\n';
// the countries in alphabetical order of their names, for each of the launcher's languages (CountryPicker.tsx sorts with localeCompare)
const codes = Object.keys(EDITIONS).sort();
const nameIn = (code, tag) => { try { const d = new Intl.DisplayNames([tag], {type: 'region'}).of(code); return d && d !== code ? d : EDITIONS[code].name; } catch { return EDITIONS[code].name; } };
out += `static const char *COUNTRY_ORDER[13][${codes.length}] = {\n`;
for (const tag of Object.values(LANGS)) out += '\t{' + codes.slice().sort((a, b) => nameIn(a, tag).localeCompare(nameIn(b, tag), tag)).map(q).join(', ') + '},\n';
out += '};\n';
out += 'static const char *NAME_LANGS[] = {' + Object.keys(LANGS).map(q).join(', ') + '};\n';
writeFileSync(new URL('../src/data/editions.inc', import.meta.url), out);
console.log('src/data/editions.inc written: ' + Object.keys(EDITIONS).length + ' countries');
