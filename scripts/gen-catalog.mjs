// Generates src/data/catalog.inc from the app catalogue (data/catalog.json): the short titles of well-known apps, their own
// icons (assets/icons/apps, copied into the package) and the monogram colours of apps without one.
// Run: node scripts/gen-catalog.mjs

import {readFileSync, writeFileSync} from 'node:fs';

const entries = JSON.parse(readFileSync(new URL('../data/catalog.json', import.meta.url), 'utf8'));
const q = (s) => JSON.stringify(s);
let out = '// Generated by scripts/gen-catalog.mjs from data/catalog.json. Do not edit.\n';
out += 'static const CatalogApp CATALOG[] = {\n';
for (const e of entries) out += `\t{${q(e.id)}, ${q(e.title)}, ${q(e.icon)}, ${q(e.color)}},\n`;
out += '};\n';
writeFileSync(new URL('../src/data/catalog.inc', import.meta.url), out);
console.log(`src/data/catalog.inc written: ${entries.length} apps`);
