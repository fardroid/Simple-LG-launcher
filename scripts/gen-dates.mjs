// Generates src/i18n/dates.inc: the names of days and months and the order of a date's parts in the launcher's 13 languages,
// from node's own Intl (the TV has no Intl for native code). English and Russian are the web version's own words (lib/clock.ts),
// the others are what the web version gets from the web view's Intl.
// Run: node scripts/gen-dates.mjs

import {writeFileSync} from 'node:fs';

const LANGS = {en: 'en', ru: 'ru', es: 'es', fr: 'fr', de: 'de', it: 'it', pt: 'pt', tr: 'tr', uk: 'uk', zh: 'zh-CN', ja: 'ja', ko: 'ko', pl: 'pl'};
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const utc = (y, m, d) => { const date = new Date(Date.UTC(2000, m, d)); date.setUTCFullYear(y); return date; };

// lib/clock.ts
const OWN = {
	en: {day: ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'],
		short: ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'],
		month: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']},
	ru: {day: ['Воскресенье', 'Понедельник', 'Вторник', 'Среда', 'Четверг', 'Пятница', 'Суббота'],
		short: ['Вс', 'Пн', 'Вт', 'Ср', 'Чт', 'Пт', 'Сб'],
		month: ['Январь', 'Февраль', 'Март', 'Апрель', 'Май', 'Июнь', 'Июль', 'Август', 'Сентябрь', 'Октябрь', 'Ноябрь', 'Декабрь'],
		inDate: ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря']}
};

// A date's parts in order: 'd' the day, 'm' the month, 'y' the year, anything else literal text. The month's own words in that
// pattern for each month (some languages use another form there, Russian "октября").
function pattern (tag, withYear) {
	const options = withYear ? {day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC'} : {day: 'numeric', month: 'long', timeZone: 'UTC'};
	const f = new Intl.DateTimeFormat(tag, options);
	const parts = f.formatToParts(utc(2026, 9, 11)).map((p) => (p.type === 'day' ? 'd' : p.type === 'month' ? 'm' : p.type === 'year' ? 'y' : {lit: p.value}));
	const months = [];
	for (let m = 0; m < 12; m++) months.push(f.formatToParts(utc(2026, m, 11)).find((p) => p.type === 'month').value);
	return {parts, months};
}

const q = (s) => JSON.stringify(s);
let out = '// Generated by scripts/gen-dates.mjs from node ' + process.version + ' (Intl). Do not edit.\n';
out += 'static const DateWords DATE_WORDS[] = {\n';
for (const [lang, tag] of Object.entries(LANGS)) {
	const own = OWN[lang];
	const day = own ? own.day : [...Array(7)].map((_, i) => cap(new Intl.DateTimeFormat(tag, {weekday: 'long', timeZone: 'UTC'}).format(utc(2000, 0, 2 + i))));
	const short = own ? own.short : [...Array(7)].map((_, i) => cap(new Intl.DateTimeFormat(tag, {weekday: 'short', timeZone: 'UTC'}).format(utc(2000, 0, 2 + i))));
	const month = own ? own.month : [...Array(12)].map((_, i) => cap(new Intl.DateTimeFormat(tag, {month: 'long', timeZone: 'UTC'}).format(utc(2000, i, 1))));
	const full = pattern(tag, true), noYear = pattern(tag, false);
	// English and Russian put it the web version's way: "11 October 2026", "11 октября 2026"
	if (lang === 'en' || lang === 'ru') {
		full.parts = ['d', {lit: ' '}, 'm', {lit: ' '}, 'y'];
		noYear.parts = ['d', {lit: ' '}, 'm'];
		full.months = noYear.months = lang === 'ru' ? own.inDate : own.month;
	}
	const encode = (parts) => parts.map((p) => (typeof p === 'string' ? '\\x01' + p : p.lit)).join('');
	// the first letter of a date is a capital, as the web version does (text.charAt(0).toUpperCase())
	out += `\t{${q(lang)}, {${day.map(q).join(', ')}}, {${short.map(q).join(', ')}}, {${month.map(q).join(', ')}},\n`;
	// \001 marks a part (octal: a hex escape would swallow the letter after it)
	const c = (parts) => JSON.stringify(encode(parts)).replace(/\\\\x01/g, '\\001');
	out += `\t\t${c(full.parts)}, {${full.months.map(q).join(', ')}},\n`;
	out += `\t\t${c(noYear.parts)}, {${noYear.months.map(q).join(', ')}}},\n`;
}
out += '};\n';
writeFileSync(new URL('../src/i18n/dates.inc', import.meta.url), out);
console.log('src/i18n/dates.inc written');
