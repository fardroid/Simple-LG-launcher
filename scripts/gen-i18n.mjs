// Generates src/i18n/locales.inc from src/i18n/locales/*.json: the translations of every text of the launcher, keyed by its
// English text. English and Russian are written where they are used, as tr(en, ru).
// Run: node scripts/gen-i18n.mjs

import {readdirSync, readFileSync, writeFileSync} from 'node:fs';

const dir = new URL('../src/i18n/locales/', import.meta.url);
const c = (s) => JSON.stringify(s);      // a C++ string literal (JSON's escapes are C's, for these texts)
let out = '// Generated by scripts/gen-i18n.mjs from src/i18n/locales/*.json. Do not edit.\n';
const langs = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
	const lang = file.replace('.json', '');
	const dict = JSON.parse(readFileSync(new URL(file, dir), 'utf8'));
	const name = 'LOCALE_' + lang.toUpperCase();
	out += `static const Entry ${name}[] = {\n`;
	for (const [k, v] of Object.entries(dict)) out += `\t{${c(k)}, ${c(v)}},\n`;
	out += '\t{nullptr, nullptr}\n};\n';
	langs.push([lang, name, Object.keys(dict).length]);
}
out += 'static const Locale LOCALES[] = {\n' + langs.map(([l, n]) => `\t{${c(l)}, ${n}},\n`).join('') + '};\n';
writeFileSync(new URL('../src/i18n/locales.inc', import.meta.url), out);
console.log('src/i18n/locales.inc written: ' + langs.map(([l, , n]) => `${l} ${n}`).join(', '));
